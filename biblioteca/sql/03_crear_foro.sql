CREATE TABLE CATEGORIAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(80) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(250)
);

CREATE TABLE TEMAS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITULO VARCHAR2(150) NOT NULL,
    CONTENIDO VARCHAR2(4000) NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CATEGORIA_ID NUMBER NOT NULL,
    AUTOR_ID NUMBER NOT NULL,
    CONSTRAINT FK_TEMAS_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS(ID),
    CONSTRAINT FK_TEMAS_AUTOR FOREIGN KEY (AUTOR_ID) REFERENCES USUARIOS(ID)
);

CREATE TABLE COMENTARIOS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONTENIDO VARCHAR2(2000) NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    TEMA_ID NUMBER NOT NULL,
    AUTOR_ID NUMBER NOT NULL,
    CONSTRAINT FK_COMENTARIOS_TEMA FOREIGN KEY (TEMA_ID) REFERENCES TEMAS(ID),
    CONSTRAINT FK_COMENTARIOS_AUTOR FOREIGN KEY (AUTOR_ID) REFERENCES USUARIOS(ID)
);

